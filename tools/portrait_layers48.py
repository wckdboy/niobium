def face(kind, blink=False):
    c=Canvas()
    sharp = kind in ("sharp","fierce","stern")
    c.line(22,10,25,11 if sharp else 10,"h")
    c.line(29,10 if sharp else 9,31,9,"h")
    if blink:
        # Skin replaces the complete open-eye footprint before the closed lash.
        c.r(22,12,4,3,"S");c.r(29,11,3,3,"S")
        c.line(23,13,25,13,"d");c.line(29,12,31,12,"d")
    else:
        c.line(22,12,25,13,"D");c.p(23,13,"W");c.p(24,13,"E")
        c.line(29,11,31,12,"D");c.p(29,12,"W");c.p(30,12,"E")
        if kind == "soft":c.p(25,14,"s")
    c.line(27,13,27,16,"s");c.p(28,16,"L");c.p(28,17,"s")
    if kind == "wry":c.line(26,19,29,18,"d");c.p(29,17,"s")
    elif kind == "fierce":c.line(26,19,29,19,"d");c.p(26,18,"L")
    elif kind == "stern":c.line(25,19,28,19,"d");c.p(28,20,"s")
    elif kind == "soft":c.line(26,19,28,19,"d");c.p(27,20,"L")
    else:c.line(26,19,29,18,"s");c.p(28,20,"L")
    return c


